/**
 * Bundle the drizzle migrations + the fresh-install seed into a TypeScript module
 * the Worker can run at runtime.
 *
 * WHY: the setup wizard (src/server/setup/*) initializes a brand-new install's
 * database from inside the Worker — no `wrangler d1 migrations apply` CLI step for
 * the buyer. To do that, the exact migration SQL has to be embedded in the bundle.
 * Rather than hand-maintain a consolidated schema (which drifts), we regenerate
 * this file from drizzle/*.sql on every build, so the runtime initializer always
 * matches the checked-in migrations.
 *
 * Output: src/db/migrations.generated.ts
 *   - SCHEMA_STATEMENTS: every migration statement, in file + in-file order.
 *   - SEED_STATEMENTS:   the fresh-install reference data (no hardcoded god).
 *
 * Run via `npm run db:bundle` (also runs automatically at the front of `build`).
 */

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const drizzleDir = join(root, 'drizzle');
const seedPath = join(root, 'src', 'db', 'seed-fresh.sql');
const outPath = join(root, 'src', 'db', 'migrations.generated.ts');

/** Strip block + line comments (but not the statement-breakpoint marker). */
function stripComments(sql) {
  return sql
    .replace(/\/\*[\s\S]*?\*\//g, '') // /* ... */
    .split('\n')
    .filter((line) => !/^\s*--(?!>\s*statement-breakpoint)/.test(line)) // -- comments, keep --> breakpoint
    .join('\n');
}

/** Split a .sql file into individual statements on the drizzle breakpoint marker. */
function splitStatements(sql) {
  return stripComments(sql)
    .split(/-->\s*statement-breakpoint/)
    .map((s) => s.trim().replace(/;\s*$/, '').trim()) // drop trailing ; (we run one stmt at a time)
    .filter((s) => s.length > 0);
}

const asLiteral = (s) => '`' + s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${') + '`';

async function main() {
  const files = (await readdir(drizzleDir))
    .filter((f) => f.endsWith('.sql'))
    .sort(); // 0000, 0001, … lexical == chronological

  const schema = [];
  for (const f of files) {
    const sql = await readFile(join(drizzleDir, f), 'utf8');
    for (const stmt of splitStatements(sql)) schema.push(stmt);
  }

  const seed = splitStatements(await readFile(seedPath, 'utf8'));

  const banner =
    '/* AUTO-GENERATED by scripts/bundle-migrations.mjs — DO NOT EDIT.\n' +
    ` * Regenerate with \`npm run db:bundle\`. Source: drizzle/*.sql (${files.length} files) + src/db/seed-fresh.sql.\n` +
    ' * Consumed by src/server/setup/schema.ts to build a fresh install\'s database in-Worker. */\n\n';

  const body =
    `export const SCHEMA_STATEMENTS: string[] = [\n` +
    schema.map((s) => '  ' + asLiteral(s) + ',').join('\n') +
    `\n];\n\nexport const SEED_STATEMENTS: string[] = [\n` +
    seed.map((s) => '  ' + asLiteral(s) + ',').join('\n') +
    `\n];\n`;

  await writeFile(outPath, banner + body, 'utf8');
  console.log(`bundle-migrations: ${schema.length} schema + ${seed.length} seed statements → ${outPath}`);
}

main().catch((err) => {
  console.error('bundle-migrations failed:', err);
  process.exit(1);
});
